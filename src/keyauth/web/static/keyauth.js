/*! keyauth.js: embeddable typing-rhythm capture. No dependencies, no build step, no eval, no storage.
 *
 *   <script src="https://KEYAUTH-HOST/v1/keyauth.js" defer></script>
 *   const k = keyauth.attach(passwordInput, {sitekey, userIdField: "#username"});
 *
 * The block between the BEGIN/END markers is generated from capture.js by scripts/sync_keyauth.py
 * (the demo page's own capture logic, so the two cannot drift). Edit capture.js, run the script; a test
 * fails if this file is out of sync. Everything outside the markers is hand-written.
 *
 * Privacy: the password is never read (input.value is not touched). Events are anonymized in the browser
 * (every key except modifiers and Enter becomes "x", codes become "k0", "k1", ...) before they are sent.
 * Only the keyauth endpoint is contacted. Docs: docs/SERVICE.md, section "Embedding".
 */
(function () {
  "use strict";

  const root = globalThis;

  // ---- BEGIN capture.js (generated by scripts/sync_keyauth.py; do not edit) ----
  // Pure keystroke-capture helpers for the keyauth demo page. No DOM access here.
  // Timestamps are milliseconds (performance.now()), like the API expects.

  const PHRASE = ".tie5Roanl";
  const SUBMIT_KEY = "Enter";
  // Same list as MODIFIER_KEYS in src/keyauth/config.py: the server drops these.
  const MODIFIER_KEYS = new Set(["Shift", "Control", "Alt", "Meta", "CapsLock", "AltGraph"]);
  // Keys that mean "the user is correcting a typo": rhythm is not comparable, start over.
  const RESET_KEYS = new Set(["Backspace", "Delete"]);
  // Length rules for a phrase we do not know (embedded login: the field holds the user's own password).
  // Counted in non-modifier keydowns, without the trailing Enter; MAX stays under the API's 128 keys.
  const MIN_PHRASE_KEYS = 4;
  const MAX_PHRASE_KEYS = 100;
  const USER_ID_PATTERN = /^[A-Za-z0-9._@-]{1,64}$/;

  function isValidUserId(value) {
    return typeof value === "string" && USER_ID_PATTERN.test(value);
  }

  // Text spelled by the non-modifier keydowns, without the trailing Enter.
  // Events are the raw ones (real key names), before anonymize().
  // With phrase === null the text is not compared: only "ends with Enter, and the length is within the rules".
  function matchesPhrase(events, phrase = PHRASE) {
    const keys = events.filter((e) => e.type === "down" && !MODIFIER_KEYS.has(e.key)).map((e) => e.key);
    if (phrase === null) {
      const typed = keys.length - 1;
      return keys[keys.length - 1] === SUBMIT_KEY && !keys.slice(0, -1).includes(SUBMIT_KEY) && typed >= MIN_PHRASE_KEYS && typed <= MAX_PHRASE_KEYS;
    }
    const expected = Array.from(phrase);
    expected.push(SUBMIT_KEY);
    if (keys.length !== expected.length) {
      return false;
    }
    return keys.every((k, i) => k === expected[i]);
  }

  // True when every keydown has a keyup (auto-repeat already filtered by the recorder).
  function isComplete(events) {
    const open = new Set();
    for (const e of events) {
      if (e.type === "down") {
        open.add(e.code);
      } else {
        open.delete(e.code);
      }
    }
    return open.size === 0;
  }

  // Remove everything that reveals what was typed. Keeps `key` only for modifiers and Enter;
  // every other key becomes "x". `code` becomes an opaque per-press id ("k0", "k1", ...) assigned
  // in order of first press, shared by the down and up of the same press, so the server (events.py
  // pair_events) still pairs them. A repeated physical key gets a new id, so repeated letters do not
  // show. Timestamps are rebased to the first event (only differences matter). Keyups without a
  // matching keydown are dropped (the server would ignore them anyway).
  function anonymize(events) {
    const sorted = events.slice();
    const openIds = new Map(); // original code -> opaque id of the press that is still held
    let next = 0;
    let origin = null;
    const out = [];
    for (const e of sorted) {
      if (origin === null) {
        origin = e.t;
      }
      let key = "x";
      if (MODIFIER_KEYS.has(e.key) || e.key === SUBMIT_KEY) {
        key = e.key;
      }
      if (e.type === "down") {
        if (openIds.has(e.code)) {
          continue; // auto-repeat that slipped through
        }
        const id = "k" + next;
        next += 1;
        openIds.set(e.code, id);
        out.push({ key, type: "down", t: e.t - origin, code: id });
      } else {
        const id = openIds.get(e.code);
        if (id === undefined) {
          continue;
        }
        openIds.delete(e.code);
        out.push({ key, type: "up", t: e.t - origin, code: id });
      }
    }
    return out;
  }

  // Collects raw events for one attempt. Feed it keydown/keyup (with performance.now() times).
  // Every method returns a result object: {status: "ok"} | {status: "reset", reason} |
  // {status: "done", events}.  (phrase === null: any password of allowed length, see matchesPhrase.)  reason: "correction" | "incomplete" | "wrong_password".
  // "done" events are already anonymized and safe to send.
  class Recorder {
    constructor(phrase = PHRASE) {
      this.phrase = phrase;
      this.reset();
    }

    reset() {
      this.events = [];
      this.held = new Set();
    }

    get length() {
      return this.events.length;
    }

    keyDown(key, code, t, repeat = false) {
      if (repeat) {
        return { status: "ok" }; // auto-repeat is not a new keystroke
      }
      if (RESET_KEYS.has(key)) {
        this.reset();
        return { status: "reset", reason: "correction" };
      }
      if (this.held.has(code)) {
        return { status: "ok" };
      }
      this.held.add(code);
      this.events.push({ key, type: "down", t, code });
      return { status: "ok" };
    }

    keyUp(key, code, t) {
      if (!this.held.has(code)) {
        return { status: "ok" }; // key was pressed before capture began
      }
      this.held.delete(code);
      this.events.push({ key, type: "up", t, code });
      if (key !== SUBMIT_KEY) {
        return { status: "ok" };
      }
      const raw = this.events;
      this.reset();
      if (!isComplete(raw)) {
        return { status: "reset", reason: "incomplete" };
      }
      if (!matchesPhrase(raw, this.phrase)) {
        return { status: "reset", reason: "wrong_password" };
      }
      return { status: "done", events: anonymize(raw) };
    }

    // paste, cut, drop, blur
    interrupt() {
      this.reset();
      return { status: "reset", reason: "correction" };
    }
  }
  // ---- END capture.js ----

  const TIMEOUT_MS = 5000;
  const TOKEN_FIELD = "keyauth_token";
  // /v1 ids are opaque: no '@' (see docs/SERVICE.md). Stricter than the demo page's USER_ID_PATTERN.
  const V1_USER_ID_PATTERN = /^[A-Za-z0-9._-]{1,64}$/;

  // The origin this script was loaded from is the default endpoint. Read it now: currentScript is
  // only set while the script runs.
  let scriptOrigin = null;
  try {
    if (document.currentScript && document.currentScript.src) {
      scriptOrigin = new URL(document.currentScript.src).origin;
    }
  } catch (e) {
    scriptOrigin = null;
  }

  const attached = new WeakMap(); // input -> instance
  const enrolling = new WeakMap(); // input -> cancel function

  function resolveEndpoint(value) {
    let base = scriptOrigin;
    if (typeof value === "string" && value !== "") {
      base = value;
    }
    if (typeof base !== "string" || !/^https?:\/\//i.test(base)) {
      return null;
    }
    return base.replace(/\/+$/, "");
  }

  // POST JSON; always resolves {ok, status, data, code}. status 0 + code "network" | "timeout" on failure.
  // Cookies and referrer are never sent. Never logs or throws.
  function post(url, body) {
    return new Promise((resolve) => {
      if (typeof fetch !== "function") {
        resolve({ ok: false, status: 0, data: null, code: "network" });
        return;
      }
      let finished = false;
      let controller = null;
      if (typeof AbortController === "function") {
        controller = new AbortController();
      }
      let timer = null;
      const finish = (result) => {
        if (finished) {
          return;
        }
        finished = true;
        clearTimeout(timer);
        resolve(result);
      };
      timer = setTimeout(() => {
        finish({ ok: false, status: 0, data: null, code: "timeout" });
        if (controller !== null) {
          controller.abort();
        }
      }, TIMEOUT_MS);
      const init = {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
        credentials: "omit",
        mode: "cors",
        cache: "no-store",
        referrerPolicy: "no-referrer",
      };
      if (controller !== null) {
        init.signal = controller.signal;
      }
      let request;
      try {
        request = fetch(url, init);
      } catch (e) {
        finish({ ok: false, status: 0, data: null, code: "network" });
        return;
      }
      Promise.resolve(request)
        .then(async (res) => {
          let data = null;
          try {
            data = await res.json();
          } catch (e) {
            data = null;
          }
          let code = "";
          if (data && data.error && typeof data.error.code === "string") {
            code = data.error.code;
          }
          finish({ ok: res.ok === true, status: res.status, data, code });
        })
        .catch(() => finish({ ok: false, status: 0, data: null, code: "network" }));
    });
  }

  function readUserId(spec, form) {
    let value = null;
    try {
      if (typeof spec === "function") {
        value = spec();
      } else if (typeof spec === "string") {
        let found = null;
        if (form) {
          found = form.querySelector(spec);
        }
        if (found === null || found === undefined) {
          found = document.querySelector(spec);
        }
        if (found) {
          value = found.value;
        }
      } else if (spec && typeof spec === "object") {
        value = spec.value;
      }
    } catch (e) {
      return null;
    }
    if (typeof value !== "string") {
      return null;
    }
    value = value.trim();
    if (!V1_USER_ID_PATTERN.test(value)) {
      return null;
    }
    return value;
  }

  // Keys of the password field feed `recorder`. Returns the recorder's result for the event.
  function feedKeyDown(recorder, e) {
    return recorder.keyDown(e.key, e.code, performance.now(), e.repeat === true);
  }

  function feedKeyUp(recorder, e) {
    return recorder.keyUp(e.key, e.code, performance.now());
  }

  function usableKey(e) {
    // autofill and some IMEs dispatch key events without a key string
    return e && typeof e.key === "string" && e.key !== "";
  }

  function attach(input, options) {
    if (!input || typeof input.addEventListener !== "function") {
      throw new TypeError("keyauth.attach: first argument must be the password input element");
    }
    const opts = Object.assign({}, options);
    if (typeof opts.sitekey !== "string" || opts.sitekey === "") {
      throw new TypeError("keyauth.attach: options.sitekey is required");
    }
    const previous = attached.get(input);
    if (previous) {
      previous.destroy(); // attaching twice replaces the first instance; listeners never stack
    }

    const endpoint = resolveEndpoint(opts.endpoint);
    let tokenField = TOKEN_FIELD;
    if (typeof opts.tokenField === "string" && opts.tokenField !== "") {
      tokenField = opts.tokenField;
    }
    const form = input.form || null;
    const recorder = new Recorder(null);
    let attempt = null; // anonymized events of a finished attempt, until used
    let token = "";
    let inflight = null;
    let passThrough = false;
    let destroyed = false;
    let hidden = null;

    if (form) {
      hidden = document.createElement("input");
      hidden.type = "hidden";
      hidden.name = tokenField;
      hidden.value = "";
      form.appendChild(hidden);
    }

    function setHidden(value) {
      if (hidden) {
        hidden.value = value;
      }
    }

    function clearAttempt() {
      attempt = null;
      token = "";
      setHidden("");
    }

    // Resolves to the token string, or "" when there is no usable attempt or keyauth did not answer.
    function getToken() {
      if (inflight !== null) {
        return inflight;
      }
      const events = attempt;
      const userId = readUserId(opts.userIdField, form);
      if (events === null || userId === null || endpoint === null) {
        if (events === null) {
          return Promise.resolve(token);
        }
        attempt = null;
        return Promise.resolve("");
      }
      attempt = null;
      inflight = post(endpoint + "/v1/verify", { sitekey: opts.sitekey, user_id: userId, events }).then((r) => {
        inflight = null;
        token = "";
        if (r.ok && r.data && typeof r.data.token === "string") {
          token = r.data.token;
        }
        if (!destroyed) {
          setHidden(token);
        }
        return token;
      });
      return inflight;
    }

    // pass = true for the continuation after keyauth answered: our own submit handler then lets it through
    function submitForm(submitter, pass) {
      passThrough = pass;
      try {
        if (typeof form.requestSubmit === "function") {
          try {
            if (submitter) {
              form.requestSubmit(submitter);
            } else {
              form.requestSubmit();
            }
          } catch (e) {
            form.requestSubmit();
          }
        } else if (form.dispatchEvent(new Event("submit", { cancelable: true, bubbles: true }))) {
          form.submit();
        }
      } finally {
        passThrough = false;
      }
    }

    function onSubmit(ev) {
      if (passThrough || destroyed) {
        return;
      }
      if (attempt === null || readUserId(opts.userIdField, form) === null || endpoint === null) {
        // nothing to ask keyauth about: let the form go, with an empty token
        attempt = null;
        setHidden("");
        return;
      }
      ev.preventDefault();
      if (typeof ev.stopImmediatePropagation === "function") {
        ev.stopImmediatePropagation();
      }
      const submitter = ev.submitter;
      // getToken never rejects; whatever happens, the form continues
      getToken().then(
        () => submitForm(submitter, true),
        () => submitForm(submitter, true)
      );
    }

    function onKeyDown(e) {
      if (destroyed || !usableKey(e)) {
        return;
      }
      if (e.isComposing === true) {
        recorder.interrupt();
        clearAttempt();
        return;
      }
      if (e.key === SUBMIT_KEY && form) {
        e.preventDefault(); // Enter is part of the rhythm: the form is submitted after its keyup
      }
      if (inflight === null && (attempt !== null || token !== "") && e.key !== SUBMIT_KEY) {
        clearAttempt();
      }
      const res = feedKeyDown(recorder, e);
      if (res.status === "reset") {
        clearAttempt();
      }
    }

    function onKeyUp(e) {
      if (destroyed || !usableKey(e)) {
        return;
      }
      const res = feedKeyUp(recorder, e);
      if (res.status === "done") {
        attempt = res.events;
      }
      if (res.status === "reset") {
        clearAttempt();
      }
      if (e.key === SUBMIT_KEY && res.status !== "ok" && form) {
        submitForm(null, false);
      }
    }

    function onInterrupt() {
      if (destroyed) {
        return;
      }
      recorder.interrupt();
      clearAttempt();
    }

    function onBlur() {
      if (!destroyed && recorder.length > 0) {
        onInterrupt();
      }
    }

    const listeners = [
      ["keydown", onKeyDown],
      ["keyup", onKeyUp],
      ["paste", onInterrupt],
      ["cut", onInterrupt],
      ["drop", onInterrupt],
      ["blur", onBlur],
    ];
    for (const [name, fn] of listeners) {
      input.addEventListener(name, fn);
    }
    if (form) {
      form.addEventListener("submit", onSubmit, true);
    }

    const instance = {
      getToken,
      reset() {
        recorder.reset();
        clearAttempt();
      },
      destroy() {
        if (destroyed) {
          return;
        }
        destroyed = true;
        for (const [name, fn] of listeners) {
          input.removeEventListener(name, fn);
        }
        if (form) {
          form.removeEventListener("submit", onSubmit, true);
        }
        if (hidden && typeof hidden.remove === "function") {
          hidden.remove();
        }
        recorder.reset();
        attempt = null;
        token = "";
        if (attached.get(input) === instance) {
          attached.delete(input);
        }
      },
    };
    attached.set(input, instance);
    return instance;
  }

  // Capture ONE attempt on the field and send it to /v1/enroll. The page calls it again for each sample.
  // Resolves {samples, required, done}; rejects with an Error whose .code is the server's error code
  // ("replay", "length_mismatch", "invalid_ticket", "rate_limited", ...) or "network" | "timeout" | "cancelled".
  function enroll(input, options) {
    return new Promise((resolve, reject) => {
      const fail = (code, status) => {
        const err = new Error("keyauth enroll failed: " + code);
        err.code = code;
        err.status = status;
        reject(err);
      };
      const opts = Object.assign({}, options);
      const endpoint = resolveEndpoint(opts.endpoint);
      if (!input || typeof input.addEventListener !== "function" || typeof opts.sitekey !== "string" || typeof opts.ticket !== "string" || opts.sitekey === "" || opts.ticket === "") {
        fail("bad_arguments", 0);
        return;
      }
      if (typeof opts.user_id !== "string" || !V1_USER_ID_PATTERN.test(opts.user_id) || endpoint === null) {
        fail("bad_arguments", 0);
        return;
      }
      const earlier = enrolling.get(input);
      if (earlier) {
        earlier();
      }
      const recorder = new Recorder(null);
      const form = input.form || null;

      function stop() {
        input.removeEventListener("keydown", onKeyDown);
        input.removeEventListener("keyup", onKeyUp);
        input.removeEventListener("paste", onInterrupt);
        input.removeEventListener("cut", onInterrupt);
        input.removeEventListener("drop", onInterrupt);
        input.removeEventListener("blur", onBlur);
        if (enrolling.get(input) === cancel) {
          enrolling.delete(input);
        }
      }

      function cancel() {
        stop();
        fail("cancelled", 0);
      }

      function onKeyDown(e) {
        if (!usableKey(e)) {
          return;
        }
        if (e.isComposing === true) {
          recorder.interrupt();
          return;
        }
        if (e.key === SUBMIT_KEY && form) {
          e.preventDefault(); // Enter ends the sample; it must not submit the customer's form
        }
        feedKeyDown(recorder, e);
      }

      function onKeyUp(e) {
        if (!usableKey(e)) {
          return;
        }
        const res = feedKeyUp(recorder, e);
        if (res.status !== "done") {
          return; // corrections, too short, paste: keep waiting for a clean attempt
        }
        stop();
        post(endpoint + "/v1/enroll", { sitekey: opts.sitekey, user_id: opts.user_id, ticket: opts.ticket, events: res.events }).then((r) => {
          if (!r.ok || !r.data || typeof r.data.samples !== "number" || typeof r.data.required !== "number") {
            if (r.ok) {
              fail("bad_response", r.status);
              return;
            }
            fail(r.code || "error", r.status);
            return;
          }
          const out = { samples: r.data.samples, required: r.data.required, done: r.data.status === "complete" };
          if (typeof r.data.reason === "string") {
            out.reason = r.data.reason; // e.g. "inconsistent": enrollment restarted from 0
          }
          resolve(out);
        });
      }

      function onInterrupt() {
        recorder.interrupt();
      }

      function onBlur() {
        if (recorder.length > 0) {
          recorder.interrupt();
        }
      }

      enrolling.set(input, cancel);
      input.addEventListener("keydown", onKeyDown);
      input.addEventListener("keyup", onKeyUp);
      input.addEventListener("paste", onInterrupt);
      input.addEventListener("cut", onInterrupt);
      input.addEventListener("drop", onInterrupt);
      input.addEventListener("blur", onBlur);
    });
  }

  root.keyauth = Object.freeze({ attach, enroll });
})();
