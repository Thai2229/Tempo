"""Keep src/tempo/web/static/tempo.js in sync with capture.js.

    python scripts/sync_tempo.py           # rewrite the generated block in tempo.js
    python scripts/sync_tempo.py --check   # exit 1 if tempo.js is out of date (a test runs this)

tempo.js is a classic script (no modules), so the pure capture logic of the demo page
(capture.js) is copied between the BEGIN/END markers with the `export ` keywords removed.
Nothing else is changed; capture.js stays the single source of the behaviour.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

STATIC = Path(__file__).resolve().parent.parent / "src" / "tempo" / "web" / "static"
CAPTURE = STATIC / "capture.js"
TARGET = STATIC / "tempo.js"
BEGIN = "  // ---- BEGIN capture.js (generated by scripts/sync_tempo.py; do not edit) ----\n"
END = "  // ---- END capture.js ----\n"


def generated_block() -> str:
    lines = []
    for line in CAPTURE.read_text(encoding="utf-8").splitlines():
        if line.startswith("export "):
            line = line[len("export ") :]
        if line.strip() == "":
            lines.append("\n")
        else:
            lines.append("  " + line + "\n")
    return "".join(lines)


def synced_text(current: str) -> str:
    start = current.index(BEGIN) + len(BEGIN)
    stop = current.index(END)
    return current[:start] + generated_block() + current[stop:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="only report whether tempo.js is in sync")
    args = parser.parse_args(argv)
    current = TARGET.read_text(encoding="utf-8")
    wanted = synced_text(current)
    if current == wanted:
        return 0
    if args.check:
        print("tempo.js is out of sync with capture.js; run: python scripts/sync_tempo.py", file=sys.stderr)
        return 1
    TARGET.write_text(wanted, encoding="utf-8")
    print("updated", TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
